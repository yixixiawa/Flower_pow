"""正式漏洞发现的**七字段契约**——字段定义、占位/套话识别。

为什么把这七项单独抽出来当"契约"，而不是在 ``record_finding`` 里写一串
``if not xxx: return``：

1. **口径要能复用**。提交时校验（闸门）与导出前复核（兜底）必须用同一套
   判据，否则会出现"登记时说合格、出报告时说不合格"的自相矛盾——两处各写
   一份必然漂移。
2. **判据要能解释**。拦截时必须告诉模型"缺哪一项、为什么算模糊"，所以每个
   字段除名字外还要带长度下限与填写提示；这些提示直接进拦截文案。
3. **判据要能测**。把"什么算套话"写成常量表，测试可以逐条覆盖，而不是靠
   人肉记。

七个字段对应一条漏洞发现能被第三方**独立复现**所需的最小信息集：

=====================  ======================================================
漏洞类型               是什么漏洞（SQLi / 任意文件读取 / 越权……）
受影响 URL            在哪个位置（完整 URL，能直接重放）
触发条件               什么前提下会触发（参数、权限、前置状态）
原始请求               实际发出去的请求（Burp 式报文）
原始响应               服务端真实返回（状态行 + 头 + 体）
漏洞成立依据           为什么这段响能证明漏洞成立（命中特征/与基线差异）
实际影响               能造成什么后果（读到什么、越权到什么、执行了什么）
=====================  ======================================================

少任何一项，"已确认漏洞"这个结论就站不住：没有原始响应是猜测，没有成立
依据是主观判断，没有实际影响则连危害等级都无从谈起。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class FieldSpec:
    """一个必填字段的元信息。``hint`` 会原样进拦截文案（模型据此补填）。"""

    key: str
    label: str
    min_chars: int
    hint: str


# 顺序即拦截文案里的展示顺序：先"是什么/在哪"，再"怎么触发"，最后"凭什么/有什么影响"。
REQUIRED_FIELDS: tuple[FieldSpec, ...] = (
    FieldSpec(
        "vuln_type",
        "漏洞类型",
        2,
        "写具体的漏洞类别，如「SQL 注入」「任意文件读取」「越权访问」；"
        "只写「漏洞」「问题」「风险」不算",
    ),
    FieldSpec(
        "url",
        "受影响 URL",
        8,
        "完整 URL（含 http(s):// 与路径），必须能直接重放；"
        "只写域名或「某接口」不算",
    ),
    FieldSpec(
        "trigger",
        "触发条件",
        10,
        "说明什么前提下会触发：参数在哪个位置、需要什么权限或凭证、"
        "依赖什么前置状态。不要只把 URL 再抄一遍",
    ),
    FieldSpec(
        "raw_request",
        "原始请求",
        12,
        "Burp 式原始请求：请求行（方法 + 路径 + HTTP 版本）+ 请求头 + 空行 + 请求体",
    ),
    FieldSpec(
        "raw_response",
        "原始响应",
        12,
        "服务端真实返回：状态行（或状态码）+ 响应头 + 响应体；"
        "只有「HTTP 200」不算，无法核对漏洞特征",
    ),
    FieldSpec(
        "basis",
        "漏洞成立依据",
        15,
        "为什么这段响应能证明漏洞成立：命中了什么特征、与什么基线不同、"
        "排除了哪些其他解释",
    ),
    FieldSpec(
        "impact",
        "实际影响",
        10,
        "能造成什么具体后果：读到了哪些数据、越权到什么角色、"
        "执行了什么命令、影响了哪些业务；「存在安全风险」这类套话不算",
    ),
)

# 字段名 → 中文标签（拦截文案与线索落库共用）
LABELS: dict[str, str] = {f.key: f.label for f in REQUIRED_FIELDS}

# ── 占位内容 ────────────────────────────────────────────────────────
# 整值等于其中之一才算占位（不做子串匹配：正文里出现"无"字太正常了）。
# 模型被要求"必须填"时最常见的敷衍写法就是这些，必须当作**没填**处理——
# 放过去等于给一条空发现盖章。
_PLACEHOLDERS: frozenset[str] = frozenset(
    {
        "待补充", "待完善", "待确认", "待定", "待填", "暂无", "无", "未知",
        "不清楚", "不知道", "不详", "省略", "同上", "见上文", "见前文",
        "详见上文", "详见报告", "略", "n/a", "na", "null", "none", "nil",
        "todo", "tbd", "xxx", "xxxx", "???", "？", "-", "--", "...",
        "…", "同上。", "无。", "见附件",
    }
)

# ── 套话 / 空话 ─────────────────────────────────────────────────────
# 这些句子**语法完整、字数达标**，但没有任何可核对的信息。只看长度会把它们
# 全部放过——这正是"报告里写满了等于没写"的根源。判定方式是：
# 去掉标点与常见虚词后，剩下的实义内容仍然是这些词的组合 → 判为空话。
_EMPTY_IMPACT: tuple[str, ...] = (
    "存在安全风险", "存在风险", "有安全风险", "有风险", "存在安全隐患",
    "存在安全隐患", "可能造成影响", "可能产生影响", "可能造成危害",
    "影响未知", "影响待评估", "危害未知", "存在漏洞", "有漏洞",
    "需要修复", "建议修复", "请修复", "应及时修复", "不安全",
    "危害较大", "危害严重", "影响较大", "影响严重", "可被利用",
    "会造成严重后果", "影响业务", "影响系统安全",
)

# 空话还可以是"通用名词 + 通用动词"的组合，例如「可能导致数据泄露」——
# 它看起来具体，但没说是**什么数据**、从**哪里**泄露。这类不做硬拦截
# （否则误伤面太大），只在字段里没有任何具体锚点时才降级。
_CONCRETE_ANCHORS: tuple[str, ...] = (
    "admin", "root", "token", "cookie", "session", "password", "passwd",
    "secret", "key", "数据库", "口令", "密码", "密钥", "凭证", "身份证",
    "手机号", "订单", "用户", "角色", "权限", "后台", "管理", "内网",
    "文件", "配置", "源码", "日志", "命令", "shell", "ssrf", "rce",
    "getshell", "读取", "写入", "删除", "篡改", "执行", "越权", "绕过",
    "登录", "接管", "遍历", "下载", "上传", "回显", "外带",
)

# ── 成立依据的可核对锚点 ─────────────────────────────────────────────
# 一条"成立依据"至少要指出**可观测的东西**：状态码、响应片段、与基线的
# 差异、命中规则……否则就是主观判断（"我觉得这里有注入"）。
_OBSERVABLE: tuple[str, ...] = (
    "响应", "回显", "返回", "差异", "不同", "基线", "匹配", "命中",
    "包含", "含有", "出现", "显示", "状态码", "响应头", "正文", "长度",
    "内容", "对比", "比较", "判断", "证明", "验证", "复现", "执行",
    "读取", "泄露", "绕过", "越权", "注入", "payload", "http",
)

# 漏洞类型的空泛写法（整值比较）
_GENERIC_TYPES: frozenset[str] = frozenset(
    {"漏洞", "问题", "风险", "安全问题", "安全漏洞", "其他", "其它", "unknown", "other"}
)

# 请求行：方法 + 目标（HTTP 版本可选——单行 payload 也认）
_REQ_LINE = re.compile(r"^\s*(?P<m>[A-Za-z]{3,10})\s+(?P<t>\S+)")
_STATUS_LINE = re.compile(r"^\s*HTTP/\d(?:\.\d)?\s+(?P<code>\d{3})\b", re.MULTILINE)

_WS = re.compile(r"\s+")


def norm(text: str) -> str:
    """归一化：去首尾空白、压缩内部空白。**不改内容**，只让比较稳定。"""
    return _WS.sub(" ", str(text or "").strip())


def is_placeholder(text: str) -> bool:
    """整值是否属于占位内容（大小写不敏感）。"""
    return norm(text).strip("。.；;：:！!").lower() in _PLACEHOLDERS


def is_empty_impact(text: str) -> bool:
    """实际影响是否只是套话。

    判定两档：
    * 整句就是套话表里的一条 → 空话；
    * 句子里有"泄露/攻击"这类通用词，但**没有任何具体锚点**（数据名、
      角色、系统、文件……）→ 也是空话。例如「可能导致数据泄露」——
      什么数据？从哪泄露？答不上来就说明还没验证到影响。
    """
    t = norm(text).strip("。.；;！!")
    if not t:
        return True
    if t in _EMPTY_IMPACT:
        return True
    # 去掉标点后整句等于套话（"存在安全风险。"）
    bare = re.sub(r"[，,。.；;：:！!？?\s]", "", t)
    if bare in {re.sub(r"[，,。.；;：:！!？?\s]", "", x) for x in _EMPTY_IMPACT}:
        return True
    low = bare.lower()
    if any(a in low for a in _CONCRETE_ANCHORS):
        return False
    # 没有任何具体锚点，却用了"可能导致 / 或可 / 可被利用"这类推测句式：
    # 「可能导致数据泄露」——什么数据、从哪泄露都答不上来，说明还没验证到影响。
    if any(h in bare for h in ("可能导致", "可能造成", "可能会", "可能被", "或可", "可被利用")):
        return True
    # 没有任何具体锚点，且仍在谈"风险/影响/危害" → 空话
    return any(k in bare for k in ("风险", "影响", "危害", "后果"))


def has_observable(text: str) -> bool:
    """成立依据里是否至少有一个可核对锚点。"""
    low = norm(text).lower()
    return any(k in low for k in _OBSERVABLE)


def looks_like_request_line(text: str) -> bool:
    """首行像不像请求行（方法 + 路径，HTTP 版本可省）。"""
    first = (str(text or "").strip().splitlines() or [""])[0]
    return bool(_REQ_LINE.match(first))


def looks_like_status_line(text: str) -> bool:
    """报文里有没有状态行（``HTTP/1.1 200``）。"""
    return bool(_STATUS_LINE.search(str(text or "")))


def is_generic_type(text: str) -> bool:
    return norm(text).strip("。.").lower() in _GENERIC_TYPES
